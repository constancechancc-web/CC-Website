const typeZh = (t) => {
  const m = t.match(/^(\d+(?:\.\d+)?)-sty Terrace\/Link House$/i);
  if (m) return m[1] + '层排屋';
  return TYPES[t] || t;
};

export const PATTERNS = [
  [/^For (Sale|Rent) · (.+)$/, (m) => (m[1] === 'Sale' ? '出售' : '出租') + ' · ' + typeZh(m[2])],
  [/^RM (.+)\/month$/, (m) => 'RM ' + m[1] + '/月'],
  [/^(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{4})$/, (m) => m[2] + '年' + (['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'].indexOf(m[1]) + 1) + '月'],
  [/^Studio · (\d+) Baths? · (.*?) ?sqft$/, (m) => '套房 · ' + m[1] + ' 浴室' + (m[2] ? ' · ' + m[2] + ' 平方尺' : '')],
  [/^(.+?) Beds? · (\d+) Baths? · (.*?) ?sqft$/, (m) => m[1] + ' 卧室 · ' + m[2] + ' 浴室' + (m[3] ? ' · ' + m[3] + ' 平方尺' : '')],
  [/^(Commercial|Industrial|Land) · (.*?) ?sqft$/, (m) => ({ Commercial: '商业', Industrial: '工业', Land: '土地' })[m[1]] + (m[2] ? ' · ' + m[2] + ' 平方尺' : '')]
];

export const norm = (s) => s.replace(/\s+/g, " ").trim().replace(/[\u2018\u2019]/g, "'");

export function translate(s) {
  const k = norm(s);
  if (!k) return null;
  if (Object.prototype.hasOwnProperty.call(ZH, k)) return ZH[k];
  for (const [re, fn] of PATTERNS) {
    const m = k.match(re);
    if (m) return fn(m);
  }
  return null;
}
